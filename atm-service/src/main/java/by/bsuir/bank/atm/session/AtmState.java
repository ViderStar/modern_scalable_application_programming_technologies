package by.bsuir.bank.atm.session;

/** Состояния конечного автомата сеанса работы с банкоматом. */
public enum AtmState {
    /** Ожидание карты: ввод её номера. */
    INSERT_CARD,
    /** Ввод PIN-кода — при входе и перед каждой следующей операцией. */
    PIN,
    /** Главное меню. */
    MENU,
    /** Снятие наличных: ввод суммы. */
    AMOUNT,
    /** Платёж: выбор оператора связи. */
    OPERATOR,
    /** Платёж: ввод номера телефона. */
    PHONE,
    /** Платёж: ввод суммы. */
    PAY_AMOUNT,
    /** Платёж: подтверждение введённых данных. */
    CONFIRM,
    /** Операция выполнена: вопрос о печати чека. */
    RECEIPT_PROMPT,
    /** Показ состояния счёта: продолжить работу или забрать карту. */
    RESULT,
    /** Сообщение о результате операции или об ошибке. */
    MESSAGE
}
